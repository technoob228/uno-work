export const READABLE_PASSWORD_MIN_LENGTH = 16;

/** Fills a typed array with random values; defaults to the Web Crypto API. */
export type RandomSource = (array: Uint32Array) => Uint32Array;

const cryptoRandom: RandomSource = (array) => globalThis.crypto.getRandomValues(array);

/** Uniform integer in [0, max) without modulo bias (rejection sampling). */
export function randomBelow(max: number, random: RandomSource = cryptoRandom): number {
  if (!Number.isInteger(max) || max <= 0 || max > 0x1_0000_0000) {
    throw new RangeError(`randomBelow: bad range ${max}`);
  }
  const range = 0x1_0000_0000;
  // Largest multiple of `max` that fits in 32 bits; values at or above it would skew.
  const limit = range - (range % max);
  const buffer = new Uint32Array(1);
  for (;;) {
    random(buffer);
    const value = buffer[0]!;
    if (value < limit) return value % max;
  }
}

/** "maple-river-4821-quartz": word-word-NNNN-word, always ≥ 16 characters. */
export function generateReadablePassword(random: RandomSource = cryptoRandom): string {
  const words = READABLE_PASSWORD_WORDS;
  for (;;) {
    const pick = () => words[randomBelow(words.length, random)]!;
    const digits = Array.from({ length: 4 }, () => String(randomBelow(10, random))).join("");
    const password = [pick(), pick(), digits, pick()].join("-");
    if (password.length >= READABLE_PASSWORD_MIN_LENGTH) return password;
  }
}

/** What "Copy link and password" puts on the clipboard. */
export function formatLinkAndPassword(link: string, password: string): string {
  return `${link}\nPassword: ${password}`;
}
